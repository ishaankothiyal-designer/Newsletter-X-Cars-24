const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const dist=path.join(__dirname,'../dist'),v10=path.join(dist,'versions/v10');
let root={innerHTML:''};
const context={window:{},document:{getElementById:id=>id==='newsletter'?root:null,querySelectorAll:()=>[],querySelector:()=>({style:{}}),documentElement:{scrollHeight:1000}},addEventListener:()=>{},innerHeight:800,scrollY:0,location:{hash:''}};
vm.runInNewContext(fs.readFileSync(path.join(dist,'stories.js'),'utf8'),context);
vm.runInNewContext(fs.readFileSync(path.join(dist,'sources.js'),'utf8'),context);
const before=JSON.stringify(context.window.PITSTOP);
vm.runInNewContext(fs.readFileSync(path.join(v10,'v10.js'),'utf8'),context);
assert.equal(JSON.stringify(context.window.PITSTOP),before,'V10 must not mutate V8 content');
const html=root.innerHTML,d=context.window.PITSTOP,sources=context.window.PITSTOP_SOURCES;
const esc=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
assert.equal((html.match(/data-story=/g)||[]).length,25);
assert.equal((html.match(/<dialog /g)||[]).length,25,'Each story has source notes in a dialog');
assert(!html.includes('<details'),'Source notes do not use inline accordions');
for(const s of d.stories){
 assert.equal(html.split(`data-story="${s.id}"`).length-1,1,s.id+' must appear once');
 const card=html.split(`data-story="${s.id}"`)[1].split('</article>')[0];
 const heading=card.match(/<h3[^>]*>(.*?)<\/h3>/s)[1].replace(/<[^>]+>/g,'');
 assert.equal(heading,esc(s.title),s.id+' exact headline');
 assert(card.includes(`<p>${esc(s.body)}</p>`),s.id+' exact body');
 assert(card.includes(esc(s.originalBody)),s.id+' full original update');
 assert(card.includes(esc(s.sourceCredit||s.credit)),s.id+' attribution');
 for(const note of [s.note,s.foot,sources.context?.[s.id],sources.unavailable?.[s.id]].filter(Boolean))assert(card.includes(esc(note)),s.id+' retained note');
 for(const source of s.sourceLinks||sources.stories?.[s.id]||[])assert(card.includes(`href="${esc(source.url)}"`),s.id+' retained source');
 const chapter=html.split(`<section class="chapter" id="${s.chapterId}"`)[1].split('</section>')[0];
 assert(chapter.includes(`data-story="${s.id}"`),s.id+' retained chapter');
}
const entry=fs.readFileSync(path.join(v10,'index.html'),'utf8');
assert(entry.includes('<base href="../../">'));assert(/src="stories\.js(?:\?[^"]*)?"/.test(entry));assert(entry.includes('src="sources.js"'));
assert(!entry.includes('press-strip')&&!entry.includes('Our world. In print.')&&!entry.includes('NEWSPAPER EDITION'),'Header has no slogans or version badges');
assert(!/<figcaption|class="front-kicker"|class="contents-strip"|class="front-feature"/.test(html),'Remove decorative captions and duplicate introductory blocks');
assert(html.includes('assets/v10/press-cover.webp'),'Use the V9-inspired cover');
const imageSources=[...html.matchAll(/src="(assets\/[^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(imageSources).size,imageSources.length,'Do not reuse the same image in multiple editorial slots');
assert(!entry.includes('reader.js'),'The swipe reader must not intercept document scrolling');
assert(!/inert|aria-hidden="true"[^>]*data-story/.test(html));
assert(html.includes('aria-label="Newsletter chapters"'));
assert(html.includes(esc(d.form)));
const css=fs.readFileSync(path.join(v10,'v10.css'),'utf8'),js=fs.readFileSync(path.join(v10,'v10.js'),'utf8');
assert(!/assets\/flatland|reference-flatland|flatland-ui|--page-stock|--paper-art/.test(html+css+js),'V10 must not render legacy Flatland art or paper treatments');
for(const match of html.matchAll(/(?:src|data-fallback)="(assets\/[^"]+)"/g))assert(fs.statSync(path.join(dist,match[1])).size>0,'Rendered asset exists: '+match[1]);
assert(css.includes('#4736FE')||css.includes('#4736fe'),'Cars24 Brand Blue retained');
console.log('V10 content passed: all 25 headlines, bodies, full updates, chapters, notes and source URLs preserved; shared data unchanged; no Flatland presentation; rendered assets exist.');
